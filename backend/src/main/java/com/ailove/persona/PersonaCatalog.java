    public static Persona find(String id) {
        if (id != null) {
            for (Persona p : ALL) {
                if (p.id().equals(id)) {
                    return p;
                }
            }
        }
        return ALL.get(0);
    }

    public static boolean exists(String id) {
        return id != null && ALL.stream().anyMatch(p -> p.id().equals(id));
    }

